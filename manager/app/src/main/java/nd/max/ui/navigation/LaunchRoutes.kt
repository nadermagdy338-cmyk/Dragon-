package nd.max.ui.navigation

/**
 * مسار **الإطلاق**: ما يُنقَر من قائمة بلا نيّة سابقة عن تطبيق بعينه.
 *
 * العطب الذي وُلدت منه هذه الدالة: `navigateTo` كانت تنقل `MaxDestination.route`
 * نفسه — أي **نمط** المسار بأقواسه — إلى `NavHostController.navigate`. ومسار مثل
 * `max_backup?pkg={pkg}` يُطابق وجهته (المعامل اختياري له قيمة افتراضية)، لكنه
 * يصل إليها وقيمةُ `pkg` هي النص `"{pkg}"` حرفيًّا. وهو نص **غير فارغ**، فينجو من
 * فلترة `isNullOrBlank` التي تفصل «قائمة التطبيقات» عن «تفصيل تطبيق واحد»، فتُفتح
 * شاشة التفصيل لحزمة لا وجود لها: تظهر فارغة بدل أن تظهر قائمتها.
 *
 * ⇒ مسار الإطلاق يُبنى بنزع الاستعلام الاختياري وحده.
 *
 * وما يبقى فيه نمطٌ بعد النزع (`app_settings/{pkg}`) **ليس** مسار إطلاق: معامله في
 * المسار لا في الاستعلام، ولا قيمة افتراضية له، ففتحُه بلا معامل خطأ برمجي لا حالة
 * مشروعة. ولهذا تُصرّح [launchRouteNeedsArgument] بذلك بدل أن يُمرَّر النمط صامتًا.
 */
internal fun launchRouteOf(route: String): String = route.substringBefore("?")

/**
 * هل يحتاج مسار الإطلاق معاملًا؟ صحيح فقط حين يبقى `{...}` في **المسار** بعد نزع
 * الاستعلام. ودالة صافية مستقلة عن Compose حتى تُقاس في اختبار JVM بلا جهاز.
 */
internal fun launchRouteNeedsArgument(route: String): Boolean =
    launchRouteOf(route).contains('{')

/**
 * هل تصلح هذه القيمة قيمةً لمعامل حزمة؟
 *
 * الفحص ليس "هل الحزمة مثبّتة" بل أضيق وألزم منه: **هل هي تشبه اسم حزمة أصلًا**.
 * واسم الحزمة في Java لا يقبل إلا حروفًا وأرقامًا و`_` وفواصل `.` ⇒ فلا يمكن أن
 * يحتوي `{` ولا `}`. أي قيمة تحملهما هي **نمطُ مسارنا** وصل قيمةً، لا معرّف حزمة.
 *
 * ولماذا هذا الحارس لزم فوق إصلاح [launchRouteOf]: الضغط في شاشة التحكم صار يبثّ
 * المسار منزوعًا، لكن **حالة التنقّل المحفوظة تنجو من التحديث**: مدخل سبق أن أُنشئ
 * بمعامل `"{pkg}"` (من نسخة سبقت الإصلاح) يُستعاد كما هو بعد تثبيت النسخة الجديدة،
 * فتُفتح شاشة تفصيل لحزمة اسمها `{pkg}` — نص لا وجود له على الجهاز. والحارس هنا
 * يُغلق ذلك المسار الذي لا يُغلقه الإصلاح، ويسقط إلى قائمة التطبيقات وهي الشاشة
 * الرئيسية المقصودة لهذين المدخلين.
 *
 * والفراغ يُرفض هنا أيضًا (`null` أو خالٍ) لأن الشاشتين تعتبرانه "بلا نيّة سابقة".
 */
internal fun isPackageArgument(value: String?): Boolean =
    !value.isNullOrBlank() && '{' !in value && '}' !in value

/**
 * مسار **حزمة بعينها**: يُبنى من سجل الوجهات بنزع النمط ووضع المعرّف مكانه.
 *
 * ولماذا دالة لا `route.replace(...)` في كل موضع: النزع كان مكرّرًا في خمس شاشات، وكل
 * موضع جديد كان فرصة لنزع خاطئ — وهو بالضبط العطب الذي وُلد منه هذا الملف. هنا موضع
 * واحد، ويُقاس في اختبار JVM بلا جهاز، **والحارس المقابل له [isPackageArgument]**.
 */
internal fun packageRouteOf(route: String, pkg: String): String = route.replace("{pkg}", pkg)

/**
 * مسار **قسم بعينه** في«معلومات الجهاز»: يُبنى من سجلّ الوجهات بنزع نمط المعامل ووضع
 * مفتاح القسم مكانه — فلا يُكتب `device_info?section=…` بيد في أي شاشة (ADR-02).
 *
 * ولازمٌ لأن الدخول من زرّ في شاشة **ليس** إطلاقًا مجرّدًا: من ضغط «الحرارة» في شاشة
 * الحرارة يريد **قسم الحرارة**، لا النظرة العامة. ولذلك تبقى [launchRouteOf] للدخول
 * المجرّد (فتنزع الاستعلام كله) وتبقى هذه للدخول الموجّه، والفرق بينهما مُقاس في JVM.
 */
internal fun deviceInfoRouteOf(wireKey: String): String =
    MaxDestination.DeviceInfo.route.replace("{section}", wireKey)
